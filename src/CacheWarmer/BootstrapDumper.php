namespace Go\Symfony\GoAopBundle\CacheWarmer;

use Composer\Autoload\ClassLoader;
use Go\Aop\Aspect;
use Go\Core\AspectKernel;
use Go\Symfony\GoAopBundle\Kernel\AspectSymfonyKernel;
use ReflectionClass;
use RuntimeException;
use Symfony\Contracts\Service\ServiceProviderInterface;

/**
 * Dumps the bootstrap file of the aspect kernel into the AOP cache directory.
 *
 * The file initializes the kernel of the application outside of the Symfony kernel, with the same
 * options and the same aspects (by class). It is the "loader" of the `vendor/bin/aspect` commands,
 * the script the cache warmer runs in a fresh process, and the file to require from config/preload.php
 * before the container preload file, so that opcache preloads the woven classes.
 *
 * All paths are written relative to the file itself where possible, like the compiled container
 * does: the cache directory can be moved or renamed (cache:clear does both) without a rebuild.
 *
 * @phpstan-import-type UserKernelOptions from AspectKernel
 */
final class BootstrapDumper
{
    public const string FILE_NAME = 'bootstrap.php';

    /**
     * @phpstan-param UserKernelOptions $options
     *
     * @param class-string<AspectSymfonyKernel>  $kernelClass
     * @param ServiceProviderInterface<Aspect>   $aspects     Aspect services, keyed by their class
     */
    public function __construct(
        private readonly array $options,
        private readonly string $kernelClass,
        private readonly ServiceProviderInterface $aspects,
    ) {}

    /**
     * Writes the bootstrap file into the given AOP cache directory and returns its path
     */
    public function dump(string $cacheDir): string
    {
        $file = rtrim($cacheDir, '/\\') . '/' . self::FILE_NAME;
        if (!is_dir($cacheDir) && !@mkdir($cacheDir, 0o777, true) && !is_dir($cacheDir)) {
            throw new RuntimeException(sprintf('Unable to create the Go! AOP cache directory "%s".', $cacheDir));
        }

        $temporaryFile = tempnam($cacheDir, 'bootstrap');
        if ($temporaryFile === false
            || file_put_contents($temporaryFile, $this->getContent($cacheDir)) === false
            || !rename($temporaryFile, $file)
        ) {
            throw new RuntimeException(sprintf('Unable to write the Go! AOP bootstrap file "%s".', $file));
        }
        @chmod($file, 0o666 & ~umask());

        return $file;
    }

    /**
     * Returns the content of the bootstrap file for the given AOP cache directory
     */
    public function getContent(string $cacheDir): string
    {
        $cacheDir = rtrim(str_replace('\\', '/', $cacheDir), '/');

        $autoloadFile = dirname(new ReflectionClass(ClassLoader::class)->getFileName() ?: '', 2) . '/autoload.php';

        $options = $this->options;
        unset($options['cacheDir']);
        $lines = ["    'cacheDir' => __DIR__,"];
        foreach ($options as $name => $value) {
            $lines[] = sprintf('    %s => %s,', var_export($name, true), $this->exportOption($name, $value, $cacheDir));
        }

        $aspectLines = [];
        foreach (array_keys($this->aspects->getProvidedServices()) as $aspectClass) {
            $aspectLines[] = sprintf('    \\%s::class,', ltrim($aspectClass, '\\'));
        }

        return <<<PHP
            <?php

            // This file has been auto-generated by GoAopBundle: it initializes the Go! AOP kernel of the
            // application outside of the Symfony kernel, with the configured options and aspects.
            //
            //  - "vendor/bin/aspect debug:aspect {$this->relativeFileHint($cacheDir)}" and the other aspect commands take it as their loader
            //  - "require" it from config/preload.php before the container preload file, so that opcache preloads
            //    the woven classes instead of the original ones
            //
            // Aspects are registered by their class only: advices can not run outside of the application.

            require_once {$this->exportPath($autoloadFile, $cacheDir)};

            return \\{$this->kernelClass}::bootstrap([
            {$this->join($lines)}
            ], [
            {$this->join($aspectLines)}
            ]);

            PHP;
    }

    /**
     * @param list<string> $lines
     */
    private function join(array $lines): string
    {
        return $lines === [] ? '' : implode("\n", $lines);
    }

    private function relativeFileHint(string $cacheDir): string
    {
        $projectDir = $this->options['appDir'] ?? null;
        $file       = $cacheDir . '/' . self::FILE_NAME;
        if (is_string($projectDir) && str_starts_with($file, rtrim(str_replace('\\', '/', $projectDir), '/') . '/')) {
            return substr($file, strlen(rtrim(str_replace('\\', '/', $projectDir), '/')) + 1);
        }

        return $file;
    }

    private function exportOption(string $name, mixed $value, string $cacheDir): string
    {
        if ($name === 'appDir' && is_string($value)) {
            return $this->exportPath($value, $cacheDir);
        }
        if (($name === 'includePaths' || $name === 'excludePaths') && is_array($value)) {
            $paths = [];
            foreach ($value as $path) {
                $paths[] = is_string($path) ? $this->exportPath($path, $cacheDir) : var_export($path, true);
            }

            return $paths === [] ? '[]' : "[\n        " . implode(",\n        ", $paths) . ",\n    ]";
        }

        return var_export($value, true);
    }

    /**
     * Exports a path relative to the directory of the bootstrap file, as an expression on __DIR__
     */
    private function exportPath(string $path, string $cacheDir): string
    {
        $normalized = rtrim(str_replace('\\', '/', $path), '/');
        if ($normalized === $cacheDir) {
            return '__DIR__';
        }
        if (str_starts_with($normalized, $cacheDir . '/')) {
            return '__DIR__ . ' . var_export(substr($normalized, strlen($cacheDir)), true);
        }

        $pathSegments  = explode('/', $normalized);
        $cacheSegments = explode('/', $cacheDir);
        $common        = 0;
        while (isset($pathSegments[$common], $cacheSegments[$common]) && $pathSegments[$common] === $cacheSegments[$common]) {
            $common++;
        }
        // Keep the path absolute when the only common ancestor is the file system root
        if ($common < 2) {
            return var_export($path, true);
        }
        $levels = count($cacheSegments) - $common;
        $suffix = implode('/', array_slice($pathSegments, $common));
        if ($suffix === '') {
            return sprintf('\dirname(__DIR__, %d)', $levels);
        }

        return sprintf('\dirname(__DIR__, %d) . %s', $levels, var_export('/' . $suffix, true));
    }
}
